#!/usr/bin/env python3
"""Create include/secrets.h with strong random credentials.

Usage:
  python scripts/make_secrets.py --sender-mac 8C:4B:14:xx:xx:xx --display-mac F0:F5:BD:xx:xx:xx
  python scripts/make_secrets.py ... --out /pfad/secrets.h

Credentials are only written to the file, never printed.
The MAC addresses are printed by `esptool read_mac` or in the boot log
("[BOOT] mac=..."). An existing file is never overwritten.
"""

from __future__ import annotations

import argparse
import re
import secrets
import string
import sys
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "include" / "secrets.h"
MAC = re.compile(r"^([0-9A-Fa-f]{2}[:-]){5}[0-9A-Fa-f]{2}$")
# No quotes/backslashes (C string), no ambiguous characters (typed on a phone).
ALPHABET = "".join(c for c in string.ascii_letters + string.digits if c not in "0O1lI")


def password(length: int = 20) -> str:
    return "".join(secrets.choice(ALPHABET) for _ in range(length))


def mac_bytes(text: str) -> str:
    if not MAC.match(text):
        raise ValueError(f"invalid MAC address: {text}")
    return ", ".join(f"0x{part.upper()}" for part in re.split(r"[:-]", text))


def render(sender_mac: str, display_mac: str, wifi_ssid: str, wifi_password: str) -> str:
    key = ", ".join(f"0x{b:02X}" for b in secrets.token_bytes(16))
    return f'''#pragma once

// Generated by scripts/make_secrets.py - device credentials. NEVER commit.
#include <cstdint>

namespace Secrets {{

constexpr const char* SenderWebSsid = "CANOBD2_Sender";
constexpr const char* SenderWebPassword = "{password()}";

constexpr const char* DisplayWebSsid = "CANOBD2_Display";
constexpr const char* DisplayWebPassword = "{password()}";

constexpr const char* WifiSsid = "{wifi_ssid}";
constexpr const char* WifiPassword = "{wifi_password}";

constexpr const char* WebUsername = "admin";
constexpr const char* WebPassword = "{password()}";
constexpr const char* ApiToken = "{secrets.token_hex(16)}";

constexpr uint8_t EspNowAesKey[16] = {{{key}}};

constexpr uint8_t DisplayPeerMac[6] = {{{mac_bytes(display_mac)}}};
constexpr uint8_t SenderAllowedMac[6] = {{{mac_bytes(sender_mac)}}};

}}
'''


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sender-mac", required=True)
    parser.add_argument("--display-mac", required=True)
    parser.add_argument("--wifi-ssid", default="", help="optional: hotspot/home WiFi for GitHub updates")
    parser.add_argument("--wifi-password", default="")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        for value in (args.wifi_ssid, args.wifi_password):
            if '"' in value or "\\" in value:
                raise ValueError("WiFi values must not contain quotes or backslashes")
        text = render(args.sender_mac, args.display_mac, args.wifi_ssid, args.wifi_password)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.out.exists():
        print(f"error: {args.out} exists - refusing to overwrite", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    args.out.chmod(0o660)
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Sign, verify and manage keys for CANOBD2Reader OTA firmware images.

The firmware only accepts OTA images that carry a valid Ed25519 signature
trailer (see lib/firmware_signing/FirmwareSignature.h for the layout).

Usage:
  # One-time: create a key pair and the public-key header for the firmware.
  python scripts/sign_firmware.py keygen --private-key ~/canobd2-signing.pem

  # Sign a build (private key from file or env FIRMWARE_SIGNING_KEY, PEM text).
  python scripts/sign_firmware.py sign .pio/build/sender/firmware.bin output/sender.bin

  # Check a signed image against the public keys compiled into the firmware.
  python scripts/sign_firmware.py verify output/sender.bin

  # Re-generate the public-key header from an existing private key.
  python scripts/sign_firmware.py export-header --private-key ~/canobd2-signing.pem

Never commit the private key. In CI it lives in the GitHub Actions secret
FIRMWARE_SIGNING_KEY.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import struct
import sys
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)

DOMAIN = b"CANOBD2-FIRMWARE-SIGNATURE-V1"
START_MAGIC = b"CANOSIG1"
END_MAGIC = b"CANOSEND"
TRAILER_SIZE = 88
DEFAULT_HEADER = Path(__file__).resolve().parents[1] / "include" / "config" / "FirmwareSigningKeys.h"
ENV_KEY = "FIRMWARE_SIGNING_KEY"


class SigningError(Exception):
    """Raised for user-facing signing problems."""


def key_id(public_key: bytes) -> int:
    """First 4 bytes of SHA-512(public key), little endian (matches firmware)."""
    return struct.unpack("<I", hashlib.sha512(public_key).digest()[:4])[0]


def raw_public_key(private_key: Ed25519PrivateKey) -> bytes:
    return private_key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
    )


def signed_message(image: bytes) -> bytes:
    return DOMAIN + hashlib.sha512(image).digest()


def is_signed(data: bytes) -> bool:
    return len(data) >= TRAILER_SIZE and data[-8:] == END_MAGIC and data[-TRAILER_SIZE:-TRAILER_SIZE + 8] == START_MAGIC


def build_trailer(image: bytes, private_key: Ed25519PrivateKey) -> bytes:
    signature = private_key.sign(signed_message(image))
    trailer = START_MAGIC + struct.pack("<II", len(image), key_id(raw_public_key(private_key))) + signature + END_MAGIC
    assert len(trailer) == TRAILER_SIZE
    return trailer


def sign_image(image: bytes, private_key: Ed25519PrivateKey) -> bytes:
    if is_signed(image):
        raise SigningError("Image is already signed")
    if not image or image[0] != 0xE9:
        raise SigningError("Input is not an ESP32 application image (magic 0xE9 missing)")
    return image + build_trailer(image, private_key)


def verify_image(data: bytes, public_keys: list[bytes]) -> int:
    """Return the key id of the matching key; raise SigningError otherwise."""
    if not is_signed(data):
        raise SigningError("Image has no signature trailer")
    image, trailer = data[:-TRAILER_SIZE], data[-TRAILER_SIZE:]
    length, kid = struct.unpack("<II", trailer[8:16])
    if length != len(image):
        raise SigningError(f"Length mismatch: trailer says {length}, image has {len(image)} bytes")
    for public_key in public_keys:
        if key_id(public_key) != kid:
            continue
        try:
            Ed25519PublicKey.from_public_bytes(public_key).verify(trailer[16:80], signed_message(image))
        except InvalidSignature as exc:
            raise SigningError("Signature is invalid") from exc
        return kid
    raise SigningError(f"Unknown signing key id 0x{kid:08X}")


def load_private_key(path: str | None) -> Ed25519PrivateKey:
    if path:
        pem = Path(path).expanduser().read_bytes()
    elif os.environ.get(ENV_KEY):
        pem = os.environ[ENV_KEY].encode()
    else:
        raise SigningError(f"No private key: pass --private-key or set {ENV_KEY}")
    key = serialization.load_pem_private_key(pem, password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise SigningError("Private key is not an Ed25519 key")
    return key


def render_header(public_keys: list[bytes]) -> str:
    entries = []
    for public_key in public_keys:
        hex_bytes = ", ".join(f"0x{b:02X}" for b in public_key)
        entries.append(f"    {{0x{key_id(public_key):08X}u, {{{hex_bytes}}}}},")
    body = "\n".join(entries)
    return (
        "#pragma once\n\n"
        "// Generated by scripts/sign_firmware.py - do not edit by hand.\n"
        "// Public Ed25519 keys accepted for OTA firmware. Keep the old key here\n"
        "// for one release when rotating, so devices can still update.\n\n"
        "#include \"FirmwareSignature.h\"\n\n"
        "namespace FirmwareSigningKeys {\n\n"
        "inline constexpr FirmwareSigning::PublicKey Trusted[] = {\n"
        f"{body}\n"
        "};\n\n"
        "inline constexpr std::size_t TrustedCount = sizeof(Trusted) / sizeof(Trusted[0]);\n\n"
        "} // namespace FirmwareSigningKeys\n"
    )


def parse_header(path: Path) -> list[bytes]:
    text = path.read_text(encoding="utf-8")
    keys = []
    for match in re.finditer(r"\{0x[0-9A-Fa-f]{8}u,\s*\{([^}]*)\}\}", text):
        values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", match.group(1))]
        if len(values) == 32:
            keys.append(bytes(values))
    if not keys:
        raise SigningError(f"No public keys found in {path}")
    return keys


def cmd_keygen(args: argparse.Namespace) -> None:
    target = Path(args.private_key).expanduser()
    if target.exists():
        raise SigningError(f"{target} already exists; refusing to overwrite a signing key")
    key = Ed25519PrivateKey.generate()
    pem = key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    target.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(pem)
    Path(args.header).write_text(render_header([raw_public_key(key)]), encoding="utf-8")
    print(f"Private key: {target} (keep secret, add as GitHub secret {ENV_KEY})")
    print(f"Public header: {args.header} key id 0x{key_id(raw_public_key(key)):08X}")


def cmd_export_header(args: argparse.Namespace) -> None:
    keys = [raw_public_key(load_private_key(args.private_key))]
    if args.keep_existing and Path(args.header).exists():
        keys += [k for k in parse_header(Path(args.header)) if k not in keys]
    Path(args.header).write_text(render_header(keys), encoding="utf-8")
    print(f"Wrote {args.header} with {len(keys)} key(s)")


def cmd_sign(args: argparse.Namespace) -> None:
    image = Path(args.input).read_bytes()
    signed = sign_image(image, load_private_key(args.private_key))
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_bytes(signed)
    print(f"Signed {args.input} -> {args.output} ({len(image)} + {TRAILER_SIZE} bytes)")


def cmd_verify(args: argparse.Namespace) -> None:
    kid = verify_image(Path(args.input).read_bytes(), parse_header(Path(args.header)))
    print(f"OK: {args.input} signed with key 0x{kid:08X}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    keygen = sub.add_parser("keygen", help="create a new signing key pair")
    keygen.add_argument("--private-key", required=True)
    keygen.add_argument("--header", default=str(DEFAULT_HEADER))
    keygen.set_defaults(func=cmd_keygen)

    export = sub.add_parser("export-header", help="write public-key header from a private key")
    export.add_argument("--private-key")
    export.add_argument("--header", default=str(DEFAULT_HEADER))
    export.add_argument("--keep-existing", action="store_true", help="keep old keys (key rotation)")
    export.set_defaults(func=cmd_export_header)

    sign = sub.add_parser("sign", help="append a signature trailer")
    sign.add_argument("input")
    sign.add_argument("output")
    sign.add_argument("--private-key")
    sign.set_defaults(func=cmd_sign)

    verify = sub.add_parser("verify", help="verify a signed image")
    verify.add_argument("input")
    verify.add_argument("--header", default=str(DEFAULT_HEADER))
    verify.set_defaults(func=cmd_verify)

    args = parser.parse_args(argv)
    try:
        args.func(args)
    except (SigningError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
